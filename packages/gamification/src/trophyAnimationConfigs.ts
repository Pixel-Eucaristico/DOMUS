export interface GetTrophyAnimationOptions {
  isLiturgical?: boolean;
  rarity?: AchievementRarity;
}

/**
 * Calcula quantas partículas ativas devem ser renderizadas com base na configuração
 * e no modo estático, limitando ao número máximo de slots suportados.
 */
export function resolveActiveParticleCount(
  config: Pick<TrophyAnimationConfig, "particles" | "particleCount">,
  isStatic: boolean = false,
  maxSlots: number = 6,
): number {
  if (isStatic) return 0;
  if (config.particles === "none" || config.particleCount <= 0) return 0;
  return Math.min(Math.floor(config.particleCount), maxSlots);
}

/**
 * Resolve a configuração de animação individual de um troféu pelo seu ID.
 * Caso o ID pertença a uma série infinita (ex: `streak_730`, `tx_1000`) ou não esteja
 * mapeado diretamente, aplica fallback determinístico por prefixo/categoria.
 */
export function getTrophyAnimationConfig(
  id?: string,
  options?: GetTrophyAnimationOptions,
): TrophyAnimationConfig {
  const normalizedId = id?.trim().toLowerCase() ?? "";

  if (
    normalizedId &&
    Object.prototype.hasOwnProperty.call(TROPHY_ANIMATION_CONFIGS, normalizedId)
  ) {
    return { ...TROPHY_ANIMATION_CONFIGS[normalizedId]! };
  }

  // Fallbacks por prefixo explícito de categoria/série infinita (avaliados antes de .includes())
  if (normalizedId.startsWith("streak_")) {
    return { ...CATEGORY_ANIMATION_PRESETS.streak! };
  }

  if (
    normalizedId.startsWith("budget_") ||
    normalizedId.startsWith("savings_") ||
    normalizedId.startsWith("wants_")
  ) {
    return { ...CATEGORY_ANIMATION_PRESETS.financial! };
  }

  if (normalizedId.startsWith("level_")) {
    return { ...CATEGORY_ANIMATION_PRESETS.level! };
  }

  if (normalizedId.startsWith("monthly_")) {
    return { ...CATEGORY_ANIMATION_PRESETS.monthly! };
  }

  if (normalizedId.startsWith("seasonal_")) {
    if (
      ["maes", "pais", "namorados", "valentine", "avos", "crianca", "familia", "mulher"].some(
        (k) => normalizedId.includes(k),
      )
    ) {
      return { ...CATEGORY_ANIMATION_PRESETS.seasonal_family! };
    }
    if (
      ["carnaval", "festa", "ano_novo", "natal", "verao", "ferias"].some((k) =>
        normalizedId.includes(k),
      )
    ) {
      return { ...CATEGORY_ANIMATION_PRESETS.seasonal_party! };
    }
    return { ...CATEGORY_ANIMATION_PRESETS.seasonal_economy! };
  }

  if (normalizedId.startsWith("lt_") || normalizedId.startsWith("dizimo_")) {
    return { ...CATEGORY_ANIMATION_PRESETS.religious! };
  }

  if (
    normalizedId.startsWith("tx_") ||
    normalizedId.startsWith("transactions_") ||
    normalizedId.includes("transaction")
  ) {
    return { ...CATEGORY_ANIMATION_PRESETS.transaction! };
  }

  if (normalizedId.includes("dizimo") || options?.isLiturgical) {
    return { ...CATEGORY_ANIMATION_PRESETS.religious! };
  }

  if (options?.rarity === "diamond") {
    return {
      ...DEFAULT_TROPHY_ANIMATION_CONFIG,
      motionSpeed: 2600,
      effectColor: "#4FC3F7",
      particleCount: 5,
    };
  }

  if (options?.rarity === "silver") {
    return {
      ...DEFAULT_TROPHY_ANIMATION_CONFIG,
      motionSpeed: 3800,
      effectColor: "#B0B0B0",
      particleCount: 2,
    };
  }

  return { ...DEFAULT_TROPHY_ANIMATION_CONFIG };
}
